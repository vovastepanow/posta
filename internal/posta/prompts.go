func init() {
	promptTemplates = append(promptTemplates,
		PromptTemplate{ID: "entity_rule", Title: "Правило имени собственного", Default: ContentEntityRule()},
		PromptTemplate{ID: "place_rule", Title: "Правило места и координат", Default: ContentPlaceRule()},
	)
}

func (a *App) PromptsPublic(ctx context.Context) []PromptTemplate {
	var saved map[string]string
	a.KVGet(ctx, "admin:prompts", &saved)
	out := make([]PromptTemplate, len(promptTemplates))
	copy(out, promptTemplates)
	for i := range out {
		out[i].Value = out[i].Default
		if v, ok := saved[out[i].ID]; ok {
			out[i].Value = v
		}
	}
	return out
}

func (a *App) PromptSave(ctx context.Context, id, value string, reset bool) error {
	var def *PromptTemplate
	for i := range promptTemplates {
		if promptTemplates[i].ID == id {
			def = &promptTemplates[i]
			break
		}
	}
	if def == nil {
		return Bad("Неизвестный промпт.")
	}
	if !reset {
		if err := validatePrompt(*def, value); err != nil {
			return err
		}
	}
	_, err := KVUpdate(a, ctx, "admin:prompts", 0, func(cur jx.M, _ bool) *jx.M {
		if cur == nil {
			cur = jx.M{}
		}
		if reset {
			delete(cur, id)
		} else {
			cur[id] = value
		}
		return &cur
	})
	return err
}

func validatePrompt(def PromptTemplate, value string) error {
	if strings.TrimSpace(value) == "" || len(value) > 30000 {
		return Bad("Промпт должен содержать от 1 до 30000 байт.")
	}
	allowed := make(map[string]bool, len(def.Variables))
	for _, v := range def.Variables {
		allowed[v] = true
	}
	for _, match := range regexp.MustCompile(`\{\{([^{}]+)\}\}`).FindAllStringSubmatch(value, -1) {
		if !allowed[match[1]] {
			return Bad("Неизвестная переменная {{%s}}.", match[1])
		}
	}
	for _, v := range def.Variables {
		if strings.Count(value, "{{"+v+"}}") != 1 {
			return Bad("Переменная {{%s}} должна встречаться ровно один раз.", v)
		}
	}
	return nil
}

func renderPrompt(value string, values map[string]string) string {
	pairs := make([]string, 0, len(values)*2)
	for k, v := range values {
		pairs = append(pairs, "{{"+k+"}}", v)
	}
	return strings.NewReplacer(pairs...).Replace(value)
}

func (u *U) prompt(id string, values map[string]string) string {
	for _, p := range u.PromptsPublic(u.Ctx) {
		if p.ID == id {
			return renderPrompt(p.Value, values)
		}
	}
	return ""
}

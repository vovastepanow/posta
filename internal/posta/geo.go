// geoCoords — координаты метки: известное место (по первому названию до запятой или целиком) — из списка, иначе числа модели, если они правдоподобны.
func geoCoords(name string, lat, lon any) (any, any) {
	key := strings.ToLower(strings.TrimSpace(strings.TrimPrefix(strings.ToLower(name), "г. ")))
	for _, k := range []string{key, strings.TrimSpace(strings.SplitN(key, ",", 2)[0]), strings.TrimSpace(key[strings.LastIndex(key, ",")+1:])} {
		if c, ok := geoKnown[k]; ok {
			return c[0], c[1]
		}
	}
	if lat == nil || lon == nil {
		return nil, nil
	}
	la, lo := jx.ToFloat(lat), jx.ToFloat(lon)
	if math.IsNaN(la) || math.IsNaN(lo) || math.Abs(la) > 90 || math.Abs(lo) > 180 || (la == 0 && lo == 0) {
		return nil, nil
	}
	return math.Round(la*1000) / 1000, math.Round(lo*1000) / 1000
}

// GeoFromAnalysis — метка из ответа модели: place, place_lat, place_lon; nil, если места нет.
func GeoFromAnalysis(a jx.M) jx.M {
	g := GeoFromPlace(a["place"])
	if g == nil {
		return nil
	}
	g["lat"], g["lon"] = geoCoords(jx.Str(g, "name"), a["place_lat"], a["place_lon"])
	return g
}

// GeoFromPlace — метка из строки place от модели; nil, если места нет.
func GeoFromPlace(v any) jx.M {
	s := strings.Trim(strings.TrimSpace(llm.StripCJK(jx.ToStr(v))), " \t\n\r«»\"'.,;")
	if s == "" || runeLen(s) < 2 {
		return nil
	}
	switch strings.ToLower(s) {
	case "нет", "нет места", "не указано", "неизвестно", "none", "null", "n/a", "-":
		return nil
	}
	return jx.M{"name": trimRunes(s, geoNameMax), "country": "", "city": "", "lat": nil, "lon": nil, "source": "ai"}
}

// GeoClean — метка из записи (в том числе из базы): нормализованная копия или nil.
func GeoClean(v any) jx.M {
	g, ok := v.(map[string]any)
	if !ok {
		return nil
	}
	name := trimRunes(strings.TrimSpace(jx.Str(g, "name")), geoNameMax)
	if name == "" {
		return nil
	}
	out := jx.M{"name": name, "country": jx.Str(g, "country"), "city": jx.Str(g, "city"), "lat": nil, "lon": nil, "source": jx.Str(g, "source")}
	if jx.Has(g, "lat") && jx.Has(g, "lon") && g["lat"] != nil && g["lon"] != nil {
		lat, lon := jx.Float(g, "lat"), jx.Float(g, "lon")
		if lat >= -90 && lat <= 90 && lon >= -180 && lon <= 180 {
			out["lat"], out["lon"] = lat, lon
		}
	}
	return out
}

// GeoFill — у метки есть название, а координат нет: любая точка внутри названного региона. Сначала список и кэш, затем короткий запрос к модели.
// Метка без названия не создаётся; если модель не ответила — остаётся одно название (следующий анализ попробует снова).
func (u *U) GeoFill(rec jx.M) {
	g := GeoClean(rec["geo"])
	if g == nil {
		return
	}
	if g["lat"] == nil {
		name := jx.Str(g, "name")
		if lat, lon := geoCoords(name, nil, nil); lat != nil {
			g["lat"], g["lon"] = lat, lon
		} else if c, ok := geoResolved.Load(name); ok {
			g["lat"], g["lon"] = c.([2]float64)[0], c.([2]float64)[1]
		} else if c, ok := u.geoAsk(name); ok {
			geoResolved.Store(name, c)
			g["lat"], g["lon"] = c[0], c[1]
		}
	}
	rec["geo"] = g
}

func (u *U) geoAsk(name string) ([2]float64, bool) {
	schema := jx.M{"type": "object", "properties": jx.M{"lat": jx.M{"type": "number"}, "lon": jx.M{"type": "number"}}, "required": []string{"lat", "lon"}}
	r, err := u.LLM.Generate(u.Ctx, &llm.Request{Role: llm.RoleText, Schema: schema, MaxTokens: 60, Temperature: 0, UserID: u.ID,
		Prompt: "Дай широту и долготу в градусах для места «" + name + "». Любая точка внутри этого региона подойдёт: центр города, страны или области. Верни JSON {\"lat\": число, \"lon\": число}."})
	if err != nil {
		return [2]float64{}, false
	}
	a := llm.DecodeJSON(r.Text)
	lat, lon := geoCoords("", a["lat"], a["lon"])
	if lat == nil {
		return [2]float64{}, false
	}
	return [2]float64{lat.(float64), lon.(float64)}, true
}
